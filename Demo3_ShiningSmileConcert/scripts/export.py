"""Demo 3: media/data.js for the player (timeline, positions, beats, music features, both thermal modes, art).
  python3 scripts/export.py"""
import csv, json, os, sys
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import concert as C
FPS = 30


def main():
    times = np.arange(int(C.DURATION * FPS) + 1) / FPS
    pos = C.positions(times)
    D = list(csv.DictReader(open(os.path.join(ROOT, "thermal", "drive_features.csv"))))
    t20 = np.array([float(r["time_s"]) for r in D])
    col = lambda k: np.array([float(r[k]) for r in D])
    vocal30 = np.interp(times, t20, col("vocal_n"))
    feats = {k: np.round(col(k), 3).tolist() for k in ("heat_drive", "cool_drive", "drums_n", "high_n", "vocal_n", "bass_n")}
    anim = dict(duration=C.DURATION, fps=FPS, bpm=C.STRUCT["bpm"], beats=C.STRUCT["beats"], bars=C.STRUCT["bars"],
                segments=[dict(t0=a, t1=b, key=k, ja=ja, en=en, stage=s) for a, b, k, ja, en, s in C.SEGMENTS],
                present=C.PRESENT, poses=C.pose_plan(), coolCues=C.cool_cues(),
                chars={"A": dict(az=np.round(pos["A"][0], 1).tolist(), d=np.round(pos["A"][1], 3).tolist(), mouth=np.round(vocal30, 2).tolist())},
                cool=dict(az=np.round(pos["C"][0], 1).tolist(), d=np.round(pos["C"][1], 3).tolist()),
                features=feats, featureRate=20,
                credits=dict(music="Shining Smile Melody — ZTMusic (Pixabay)", art="Character & stage art: ChatGPT (from the Demo 2 design)"))
    art_dir = os.path.join(ROOT, "media", "art")
    art = sorted(x[:-5] for x in os.listdir(art_dir) if x.endswith(".webp"))
    faces = json.load(open(os.path.join(art_dir, "faces.json")))
    with open(os.path.join(ROOT, "media", "data.js"), "w") as f:
        f.write("// generated by scripts/export.py — do not edit\nwindow.DEMO_DATA = ")
        json.dump(dict(anim=anim, thermalCsv=open(os.path.join(ROOT, "thermal", "thermal_mode_B.csv")).read(),
                       thermalCsvA=open(os.path.join(ROOT, "thermal", "thermal_mode_A.csv")).read(), art=art, artFaces=faces),
                  f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"data.js {os.path.getsize(os.path.join(ROOT, 'media', 'data.js')) // 1024} KB | {len(anim['poses'])} poses | art {len(art)}")


if __name__ == "__main__":
    main()
