"""Demo 5: subtitles (Japanese + English only) and media/data.js for the player.   python3 scripts/export.py"""
import json, os, sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import banquet as BQ
from demo1 import load
E1 = load("export")                       # Demo 1: ts(), mouth()
AUD, MEDIA, STEMS = os.path.join(ROOT, "audio"), os.path.join(ROOT, "media"), os.path.join(ROOT, "audio", "stems")
FPS = 30


def main():
    timing = json.load(open(os.path.join(AUD, "voice_timing.json")))
    items = []
    for c, tm in zip(BQ.CUES, timing):
        if c["kind"] not in ("say", "whisper", "laugh"): continue
        items.append(dict(t0=c["t"], t1=c["t"] + max(tm["dur"], .9) + .45, who=c["who"], ja=c["ja"], en=c["en"], kind=c["kind"]))
    os.makedirs(os.path.join(ROOT, "video"), exist_ok=True)
    for lang in ("ja", "en"):
        vtt, srt = ["WEBVTT", ""], []
        for i, it in enumerate(items, 1):
            nm = BQ.NAMES[it["who"]][lang]
            vtt += [f"{E1.ts(it['t0'])} --> {E1.ts(it['t1'])}", f"<v {BQ.NAMES[it['who']]['en']}>{nm}：{it[lang]}", ""]
            srt += [str(i), f"{E1.ts(it['t0'], ',')} --> {E1.ts(it['t1'], ',')}", f"{nm}：{it[lang]}", ""]
        open(os.path.join(MEDIA, f"subs_{lang}.vtt"), "w").write("\n".join(vtt))
        open(os.path.join(ROOT, "video", f"subs_{lang}.srt"), "w").write("\n".join(srt))
    times = np.arange(int(BQ.DURATION * FPS) + 1) / FPS
    pos = BQ.positions(times)
    E1.FPS = FPS
    env = lambda stem: np.round(E1.mouth(os.path.join(STEMS, stem), times), 2).tolist()
    src = lambda k, stem: dict(az=np.round(pos[k][0], 1).tolist(), d=np.round(pos[k][1], 3).tolist(), env=env(stem))
    anim = dict(duration=BQ.DURATION, fps=FPS, present=BQ.PRESENT, subs=items, names=BQ.NAMES,
                scenes=[dict(t=t, n=n, ja=ja, en=en) for t, n, ja, en in BQ.SCENES],
                chars={"N": dict(**src("N", "N_voice.wav")), "I": dict(**src("I", "I_voice.wav"))},
                cool=src("C", "C_cool.wav"), warm=src("F", "F_warm.wav"),
                cues=[dict(t=c["t"], who=c["who"], kind=c["kind"], emo=c.get("emo"), pose=c.get("pose"), dur=round(tm["dur"], 2),
                           az=c.get("az"), az1=c.get("az1"), d=c.get("d")) for c, tm in zip(BQ.CUES, timing)],
                voice=json.load(open(os.path.join(MEDIA, "voice.json"))))
    json.dump(anim, open(os.path.join(MEDIA, "anim.json"), "w"), separators=(",", ":"), ensure_ascii=False)
    art_dir = os.path.join(MEDIA, "art")
    art = sorted(x[:-5] for x in os.listdir(art_dir) if x.endswith(".webp"))
    faces = json.load(open(os.path.join(art_dir, "faces.json")))
    with open(os.path.join(MEDIA, "data.js"), "w") as f:
        f.write("// generated by scripts/export.py — do not edit\nwindow.DEMO_DATA = ")
        json.dump(dict(anim=anim, thermalCsv=open(os.path.join(MEDIA, "thermal.csv")).read(), art=art, artFaces=faces),
                  f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"subtitles: {len(items)} lines (ja/en) | art {len(art)} | data.js {os.path.getsize(os.path.join(MEDIA, 'data.js')) // 1024} KB")


if __name__ == "__main__":
    main()
