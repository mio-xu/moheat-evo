"""Subtitles (ja / en, plus zh for reference) and media/anim.json for the web demo.

  python3 tools/export.py      (after build_audio.py)
"""
import json, os, subprocess, sys
import numpy as np
from scipy.io import wavfile

sys.path.insert(0, os.path.dirname(__file__))
import story as S

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT, MEDIA, STEMS = (os.path.join(ROOT, d) for d in ("output", "media", "output/stems"))
FPS = 30


def ts(t, sep="."):
    h, r = divmod(t, 3600); m, s = divmod(r, 60)
    return f"{int(h):02d}:{int(m):02d}:{int(s):02d}{sep}{int(round((s % 1) * 1000)) % 1000:03d}"


def subtitle_items(timing):
    items = []
    for c, tm in zip(S.CUES, timing):
        if c.get("nosub") or not c["ja"]: continue
        who = "KH" if c.get("duet") else c["who"]
        items.append(dict(t0=c["t"], t1=c["t"] + max(tm["dur"], 0.9) + 0.45, who=who,
                          ja=c["ja"], en=c["en"], zh=c["zh"], kind=c["kind"]))
    return items


def name(who, lang):
    key = {"ja": "name_ja", "en": "name_en", "zh": "name_zh"}[lang]
    return " & ".join(S.CHARACTERS[w][key] for w in who)


def write_subs(items):
    for lang in ("ja", "en", "zh"):
        vtt = ["WEBVTT", ""]
        srt = []
        for i, it in enumerate(items, 1):
            txt = it[lang]
            vtt += [f"{ts(it['t0'])} --> {ts(it['t1'])}", f"<v {name(it['who'], 'en')}>{name(it['who'], lang)}：{txt}", ""]
            srt += [str(i), f"{ts(it['t0'], ',')} --> {ts(it['t1'], ',')}", f"{name(it['who'], lang)}：{txt}", ""]
        if lang != "zh":
            open(os.path.join(MEDIA, f"subs_{lang}.vtt"), "w").write("\n".join(vtt))
        open(os.path.join(OUT, f"subs_{lang}.srt"), "w").write("\n".join(srt))
        open(os.path.join(OUT, f"subs_{lang}.vtt"), "w").write("\n".join(vtt))


def mouth(path, times):
    tmp = path + ".tmp.wav"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", path, "-c:a", "pcm_f32le", tmp], check=True)
    sr, x = wavfile.read(tmp); os.remove(tmp)
    h = int(sr / FPS)
    c = np.concatenate([[0.0], np.cumsum(x.astype(np.float64) ** 2)])
    i = np.clip((times * sr).astype(int), h, len(x) - h)
    d = 10 * np.log10((c[i + h] - c[i - h]) / (2 * h) + 1e-12)
    ref = np.percentile(d[d > -60], 90)
    return np.clip((d - (ref - 26)) / 26, 0, 1)


def main():
    timing = json.load(open(os.path.join(OUT, "voice_timing.json")))
    items = subtitle_items(timing)
    write_subs(items)
    times = np.arange(int(S.DURATION * FPS) + 1) / FPS
    pos = S.positions(times)
    anim = dict(duration=S.DURATION, fps=FPS, scenes=[dict(t=t, n=n, ja=ja, en=en) for t, n, ja, en in S.SCENES],
                present=S.PRESENT, subs=items, chars={},
                voice=json.load(open(os.path.join(MEDIA, "voice.json"))))
    for who in "KH":
        az, d = pos[who]
        anim["chars"][who] = dict(az=np.round(az, 1).tolist(), d=np.round(d, 3).tolist(),
                                  mouth=np.round(mouth(os.path.join(STEMS, f"{who}_voice.wav"), times), 2).tolist(),
                                  breath=np.round(mouth(os.path.join(STEMS, f"{who}_breath.wav"), times), 2).tolist())
    anim["cues"] = [dict(t=c["t"], who=c["who"], kind=c["kind"], expr=c["expr"], style=c.get("style"),
                         dur=round(tm["dur"], 2)) for c, tm in zip(S.CUES, timing)]
    json.dump(anim, open(os.path.join(MEDIA, "anim.json"), "w"), separators=(",", ":"))
    # bundle for the web demo (works from file:// too — no fetch needed)
    csv_text = open(os.path.join(MEDIA, "thermal.csv")).read()
    with open(os.path.join(MEDIA, "data.js"), "w") as f:
        f.write("// generated by tools/export.py — do not edit\nwindow.DEMO_DATA = ")
        art_dir = os.path.join(ROOT, "..", "_kit", "snowfox", "art")   # prepared by tools/prepare_art.py
        art = sorted(x[:-5] for x in os.listdir(art_dir) if x.endswith(".webp")) if os.path.isdir(art_dir) else []
        faces_p = os.path.join(art_dir, "faces.json")
        faces = json.load(open(faces_p)) if os.path.exists(faces_p) else {}
        json.dump(dict(anim=anim, thermalCsv=csv_text, art=art, artFaces=faces), f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"subtitles: {len(items)} lines (ja/en vtt+srt, zh srt) | anim.json {os.path.getsize(os.path.join(MEDIA, 'anim.json')) // 1024} KB")


if __name__ == "__main__":
    main()
