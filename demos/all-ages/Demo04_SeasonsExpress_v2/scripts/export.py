"""Demo 4: player media → media/ (WebP art, data.js, mix.m4a, thermal.csv)

  python3 scripts/export.py        (after build_audio.py and thermal.py)
"""
import json, os, shutil, sys
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import seasons as S

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEDIA = os.path.join(ROOT, "media"); ART = os.path.join(MEDIA, "art")
RADAR_RATE = 10
ZH = dict(winter="冬日雪林", summer="盛夏海岸", storm="热带暴雨", tunnel="冰火隧道", chaos="四季失控", spring="春日樱花站")
ICONS = dict(winter_wind="🌬", snow="❄", ice_cracking="🧊", summer_breeze="🍃", ocean_waves="🌊", tropical_rain="🌧", water_drops="💧",
             thunder="⚡", fire_crackling="🔥", lava="🌋", steam="♨", spring_breeze="🌸", birds="🐦")


def art():
    os.makedirs(ART, exist_ok=True)
    n = 0
    for folder in sorted(os.listdir(os.path.join(ROOT, "assets"))):
        d = os.path.join(ROOT, "assets", folder)
        if not os.path.isdir(d): continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".png") or f.endswith("_master.png") or f == "window_mask.png": continue
            if folder not in ("winter", "summer", "rainforest", "ice_fire", "spring", "seasonal_chaos", "reused_assets"): continue   # v2: carriage = prepare_art.py, conductor = build_stage.py
            im = Image.open(os.path.join(d, f)); im.load()
            if im.mode not in ("RGBA", "RGB"): im = im.convert("RGBA")
            if f.startswith("fx_"): im = im.resize((256, 256), Image.LANCZOS)              # sprites are drawn ≤ 180 px
            im.save(os.path.join(ART, f[:-4] + ".webp"), quality=86, method=5); n += 1
    return sorted(x[:-5] for x in os.listdir(ART) if x.endswith(".webp")), n


def main():
    names, n = art()
    t = np.arange(int(S.DURATION * RADAR_RATE) + 1) / RADAR_RATE
    sources = {}
    for name, s in S.SOURCES.items():
        if name not in ICONS: continue
        if "env" in s: e = S.env(name, t)
        else:                                                            # event sources: 1.5 s bump per event
            e = np.zeros_like(t)
            for te, _, g in s["events"]: e = np.maximum(e, g * np.clip(1 - np.abs(t - te - .5) / 1.2, 0, 1))
        sources[name] = dict(role=s["role"], icon=ICONS[name], d=s["d"], env=np.round(e, 2).tolist(), az=np.round(S.azimuth(name, t)).tolist())
    anim = dict(duration=S.DURATION, fps=S.FPS, silence=list(S.SILENCE), tunnelSwap=list(S.TUNNEL_SWAP),
                warp=dict(old=S.WARP_OLD, new=S.WARP_NEW),
                segments=[dict(t0=a, t1=b, key=k, ja=ja, en=en, left=l, right=r) for a, b, k, ja, en, l, r in S.SEGMENTS],
                chaos=[dict(t0=a, t1=b, left=l, right=r) for a, b, l, r in S.CHAOS], cues=S.VISUAL_CUES,
                radarRate=RADAR_RATE, sources=sources,
                scenes=[dict(t=a, ja=ja, en=en, zh=ZH[k]) for a, b, k, ja, en, l, r in S.SEGMENTS],
                runeOpen=S.RUNE_OPEN, designed={n: dict(side=d["side"], role=d["role"], keys=d["keys"]) for n, d in S.DESIGNED.items()},
                credits=dict(art="Art: carriage, conductor & scenery — OpenAI image generation · conductor voice: ElevenLabs · every other sound is generated procedurally"))
    geo = {}
    csv_text = open(os.path.join(ROOT, "thermal", "thermal_4ch.csv")).read()
    with open(os.path.join(MEDIA, "data.js"), "w") as f:
        f.write("// generated by scripts/export.py — do not edit\nwindow.DEMO_DATA = ")
        json.dump(dict(anim=anim, geo=geo, thermalCsv=csv_text, art=names), f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    shutil.copy(os.path.join(ROOT, "audio", "final", "mix.m4a"), os.path.join(MEDIA, "mix.m4a"))
    shutil.copy(os.path.join(ROOT, "thermal", "thermal_4ch.csv"), os.path.join(MEDIA, "thermal.csv"))
    kb = sum(os.path.getsize(os.path.join(ART, x)) for x in os.listdir(ART)) // 1024
    print(f"art {n} webp ({kb} KB) | data.js {os.path.getsize(os.path.join(MEDIA, 'data.js')) // 1024} KB")


if __name__ == "__main__":
    main()
