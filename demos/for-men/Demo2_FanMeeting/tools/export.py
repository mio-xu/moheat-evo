"""Demo 2: subtitles (ja / zh / en) and media/data.js for the player.   python3 tools/export.py"""
import json, os, sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fanmeeting as FM
from demo1 import load
E1 = load("export")                       # Demo 1: ts(), mouth()  (envelope from a stem)
OUT, MEDIA, STEMS = os.path.join(ROOT, "output"), os.path.join(ROOT, "media"), os.path.join(ROOT, "output", "stems")
FPS = 30
NAME = {"ja": "綾音", "en": "Ayane"}   # subtitles: Japanese + English only


def main():
    timing = json.load(open(os.path.join(OUT, "voice_timing.json")))
    items = []
    for c, tm in zip(FM.CUES, timing):
        if not c.get("ja"): continue
        items.append(dict(t0=c["t"], t1=c["t"] + max(tm["dur"], .9) + .45, who="A", ja=c["ja"], zh=c["zh"], en=c["en"], kind=c["kind"]))
    for lang in ("ja", "en"):
        vtt, srt = ["WEBVTT", ""], []
        for i, it in enumerate(items, 1):
            vtt += [f"{E1.ts(it['t0'])} --> {E1.ts(it['t1'])}", f"<v Ayane>{NAME[lang]}：{it[lang]}", ""]
            srt += [str(i), f"{E1.ts(it['t0'], ',')} --> {E1.ts(it['t1'], ',')}", f"{NAME[lang]}：{it[lang]}", ""]
        open(os.path.join(MEDIA, f"subs_{lang}.vtt"), "w").write("\n".join(vtt))
        open(os.path.join(OUT, f"subs_{lang}.srt"), "w").write("\n".join(srt))
    times = np.arange(int(FM.DURATION * FPS) + 1) / FPS
    pos = FM.positions(times)
    E1.FPS = FPS
    env = lambda stem: np.round(E1.mouth(os.path.join(STEMS, stem), times), 2).tolist()
    anim = dict(duration=FM.DURATION, fps=FPS, present=FM.PRESENT, subs=items,
                scenes=[dict(t=t, n=n, ja=ja, zh=zh, en=en) for t, n, ja, zh, en in FM.SCENES],
                chars={"A": dict(az=np.round(pos["A"][0], 1).tolist(), d=np.round(pos["A"][1], 3).tolist(),
                                 mouth=env("heat_voice.wav"), breath=env("heat_breath.wav"))},
                cool=dict(az=np.round(pos["C"][0], 1).tolist(), d=np.round(pos["C"][1], 3).tolist(), env=env("cool_dry.wav")),
                cues=[dict(t=c["t"], kind=c["kind"], expr=c.get("expr"), pose=c.get("pose"), dur=round(tm["dur"], 2),
                           az=c.get("az"), az1=c.get("az1"), d=c.get("d")) for c, tm in zip(FM.CUES, timing)],
                voice=json.load(open(os.path.join(MEDIA, "voice.json"))))
    json.dump(anim, open(os.path.join(MEDIA, "anim.json"), "w"), separators=(",", ":"), ensure_ascii=False)
    art_dir = os.path.join(MEDIA, "art")
    art = sorted(x[:-5] for x in os.listdir(art_dir) if x.endswith(".webp")) if os.path.isdir(art_dir) else []
    faces = json.load(open(os.path.join(art_dir, "faces.json"))) if os.path.exists(os.path.join(art_dir, "faces.json")) else {}
    with open(os.path.join(MEDIA, "data.js"), "w") as f:
        f.write("// generated by tools/export.py — do not edit\nwindow.DEMO_DATA = ")
        json.dump(dict(anim=anim, thermalCsv=open(os.path.join(MEDIA, "thermal.csv")).read(), art=art, artFaces=faces),
                  f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"subtitles: {len(items)} lines (ja/en) | art {len(art)} | data.js {os.path.getsize(os.path.join(MEDIA, 'data.js')) // 1024} KB")


if __name__ == "__main__":
    main()
