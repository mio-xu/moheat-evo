#!/usr/bin/env python3
"""Generates live/index.html (the PRIVATE live-talk page, served only by tools/talk/server.py at /live/inn) from index.html, so the two
never drift apart: same layout and story, <base href="../">, the live brain (live/live.js) before main.js, noindex, different credits.
Edit index.html, then: python3 scripts/pages.py"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
rep = [('<meta charset="utf-8" />', '<meta charset="utf-8" />\n  <base href="../" />\n  <!-- GENERATED by scripts/pages.py from index.html — PRIVATE live page (tools/talk/server.py /live/inn), do not edit -->'),
       ('<meta name="robots" content="noindex" />', '<meta name="robots" content="noindex, nofollow" />'),
       ('free talk = scripted preview', 'free talk = live AI (private)'),
       ('  <script src="main.js', '  <script src="live/live.js?v=1"></script>\n  <script src="main.js')]
for a, b in rep:
    assert a in s, a; s = s.replace(a, b, 1)
os.makedirs(os.path.join(ROOT, 'live'), exist_ok=True)
open(os.path.join(ROOT, 'live', 'index.html'), 'w', encoding='utf-8').write(s); print('live/index.html')
