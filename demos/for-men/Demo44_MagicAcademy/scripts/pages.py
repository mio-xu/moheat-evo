#!/usr/bin/env python3
"""Generates live/index.html (the PRIVATE live-talk page, served only by tools/talk/server.py at /live/academy) from index.html, so the two never
drift apart: same layout and story, <base href="../">, the live brain before main.js, no shared shell (its own Start button), noindex.
Edit index.html, then: python3 scripts/pages.py"""
import hashlib, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
C = json.load(open(os.path.join(ROOT, 'cover.json'), encoding='utf-8'))
sha = lambda p: hashlib.sha1(open(os.path.join(ROOT, p), 'rb').read()).hexdigest()[:8]
head = f'<p class="kicker">MoHeat Evo · private live talk</p>\n            <h1>{C["title"]["ja"].replace(chr(10), "")}</h1>\n            <p class="en">{C["title"]["en"].replace(chr(10), " ")}</p>\n            '
rep = [('<html lang="ja" data-u2>', '<html lang="ja">'),
       ('<meta charset="utf-8" />', '<meta charset="utf-8" />\n  <base href="../" />\n  <!-- GENERATED by scripts/pages.py from index.html: PRIVATE live page (tools/talk/server.py), do not edit -->'),
       ('<meta name="robots" content="noindex" />', '<meta name="robots" content="noindex, nofollow" />'),
       ('free talk = scripted preview', 'free talk = live AI (private)'),
       ('<p class="cleared" id="cleared" hidden></p>', head + '<p class="cleared" id="cleared" hidden></p>'),
       ('  <script src="main.js', f'  <script src="../../shared/story_live.js?v={sha("../../shared/story_live.js")}"></script>\n  <script src="live/live.js?v={sha("live/live.js")}"></script>\n  <script src="main.js')]
for a, b in rep:
    assert a in s, a; s = s.replace(a, b, 1)
s, n = re.subn(r'  <script src="\.\./\.\./shared/shell\.js\?v=\w+"></script>\n', '', s); assert n == 1
open(os.path.join(ROOT, 'live', 'index.html'), 'w', encoding='utf-8').write(s); print('live/index.html')
