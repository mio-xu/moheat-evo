"""Demo 6: whisky art → media/art/*.webp, subtitles (ja + en; your lines are subtitle-only) and media/data.js.
Character / room art is NOT copied: the player loads it from the Sengoku demo's media/art (artBase in data.js).
  python3 scripts/make_export.py"""
import glob, json, os, sys
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import whisky as WK
from sengoku import ROOT, SENGOKU, TH as T5
AUD, MEDIA, STEMS = os.path.join(ROOT, "audio"), os.path.join(ROOT, "media"), os.path.join(ROOT, "audio", "stems")
FPS = 30


def ts(t, sep="."):
    h, r = divmod(t, 3600); m, s = divmod(r, 60)
    return f"{int(h):02d}:{int(m):02d}:{int(s):02d}{sep}{int(round((s % 1) * 1000)) % 1000:03d}"


def envelope(path, times):
    sr, x = T5.T1.read_mono(path)
    h = int(sr / FPS); c = np.concatenate([[0.0], np.cumsum(x ** 2)])
    i = np.clip((times * sr).astype(int), h, len(x) - h)
    d = 10 * np.log10((c[i + h] - c[i - h]) / (2 * h) + 1e-12)
    ref = np.percentile(d[d > -60], 90)
    return np.round(np.clip((d - (ref - 26)) / 26, 0, 1), 2).tolist()


def art():
    out = os.path.join(MEDIA, "art"); os.makedirs(out, exist_ok=True)
    for f in sorted(glob.glob(os.path.join(ROOT, "assets", "whisky", "*.png"))):
        im = Image.open(f).convert("RGBA"); im.thumbnail((900, 900), Image.LANCZOS)
        im.save(os.path.join(out, "w_" + os.path.basename(f)[:-4] + ".webp"), "WEBP", quality=88, method=6)
    return sorted(x[:-5] for x in os.listdir(out) if x.endswith(".webp"))


def main():
    own = art()
    timing = json.load(open(os.path.join(AUD, "voice_timing.json")))
    items = []
    for c, tm in zip(WK.CUES, timing):
        if c["kind"] in ("say", "whisper", "laugh"):
            items.append(dict(t0=c["t"], t1=c["t"] + max(tm["dur"], .9) + .45, who=c["who"], ja=c["ja"], en=c["en"], kind=c["kind"]))
        elif c["kind"] == "you":
            items.append(dict(t0=c["t"], t1=c["t"] + c["dur"], who="Y", ja=c["ja"], en=c["en"], kind="you"))
    items.sort(key=lambda x: x["t0"])
    os.makedirs(os.path.join(ROOT, "video"), exist_ok=True)
    for lang in ("ja", "en"):
        vtt, srt = ["WEBVTT", ""], []
        for i, it in enumerate(items, 1):
            nm = WK.NAMES[it["who"]][lang]
            vtt += [f"{ts(it['t0'])} --> {ts(it['t1'])}", f"<v {WK.NAMES[it['who']]['en']}>{nm}：{it[lang]}", ""]
            srt += [str(i), f"{ts(it['t0'], ',')} --> {ts(it['t1'], ',')}", f"{nm}：{it[lang]}", ""]
        open(os.path.join(MEDIA, f"subs_{lang}.vtt"), "w").write("\n".join(vtt))
        open(os.path.join(ROOT, "video", f"subs_{lang}.srt"), "w").write("\n".join(srt))
    times = np.arange(int(WK.DURATION * FPS) + 1) / FPS
    pos = WK.positions(times)
    src = lambda k, stem: dict(az=np.round(pos[k][0], 1).tolist(), d=np.round(pos[k][1], 3).tolist(), env=envelope(os.path.join(STEMS, stem), times))
    zero = dict(az=[0.0] * len(times), d=[3.0] * len(times), env=[0.0] * len(times))
    anim = dict(duration=WK.DURATION, fps=FPS, present=WK.PRESENT, subs=items, names=WK.NAMES, title=WK.TITLE,
                scenes=[dict(t=t, n=n, ja=ja, en=en) for t, n, ja, en in WK.SCENES],
                chars={"N": src("N", "N_voice.wav"), "I": src("I", "I_voice.wav")}, cool=src("C", "C_cool.wav"), warm=zero,
                cues=[dict(t=c["t"], who=c["who"], kind=c["kind"], emo=c.get("emo"), pose=c.get("pose"), dur=round(tm["dur"], 2),
                           az=c.get("az"), az1=c.get("az1"), d=c.get("d"), name=c.get("name")) for c, tm in zip(WK.CUES, timing)],
                voice=json.load(open(os.path.join(MEDIA, "voice.json"))))
    s_art = os.path.join(ROOT, "..", "_kit", "art")   # nobunaga-suntory category kit (cast + banquet room)
    base = os.path.relpath(s_art, ROOT) + "/"
    shared = sorted(x[:-5] for x in os.listdir(s_art) if x.endswith(".webp"))
    faces = json.load(open(os.path.join(s_art, "faces.json")))
    with open(os.path.join(MEDIA, "data.js"), "w") as f:
        f.write("// generated by scripts/make_export.py — do not edit\nwindow.DEMO_DATA = ")
        json.dump(dict(anim=anim, thermalCsv=open(os.path.join(MEDIA, "thermal.csv")).read(), art=shared, artBase=base,
                       ownArt=own, artFaces=faces), f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"subtitles: {len(items)} lines ({sum(i['who'] == 'Y' for i in items)} yours, text only) | shared art {len(shared)} from {base} | "
          f"whisky art {len(own)} | data.js {os.path.getsize(os.path.join(MEDIA, 'data.js')) // 1024} KB")


if __name__ == "__main__":
    main()
