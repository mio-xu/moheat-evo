#!/usr/bin/env python3
"""Asset library index: reusable background plates, props / FX sprites, character layers and synthesized SFX of every demo
(user 2026-11-08 提效标准「场景 / 道具 / 音效素材库」). Writes docs/library.md (tmp + os.replace).

  python3 tools/library/index.py            # rebuild docs/library.md
  python3 tools/library/index.py --print    # print, write nothing

Reuse rule (DEMO_DESIGN_GUIDE §12.1): a demo never loads another demo's file. To reuse: same category → move the file into
demos/<category>/_kit/ (and the original demo loads it from there); other category → copy it into your own folder.
"""
import glob, os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
IMG = ('.webp', '.png', '.jpg', '.jpeg')


def size(p):
    try:
        from PIL import Image
        with Image.open(p) as im: return f'{im.width}×{im.height}'
    except Exception: return ''


def rel(p): return os.path.relpath(p, REPO)


def owner(p):
    m = re.match(r'demos/([^/]+)/([^/]+)/', rel(p)); return (m.group(1), m.group(2)) if m else ('', '')


def images(pattern):
    out = []
    for p in sorted(glob.glob(os.path.join(REPO, 'demos', '*', '*', pattern), recursive=True)):
        if p.lower().endswith(IMG) and '/assets/' not in p and not os.path.islink(p): out.append(p)
    return out


def sfx_names(path):
    """names a synthesized-audio module exposes (the object it returns / exports) + fx keys it switches on."""
    t = open(path, encoding='utf-8', errors='ignore').read()
    names = set()
    m = list(re.finditer(r'return\s*\{([^{}]{0,1500})\}\s*;?\s*\}\)\(\)', t))
    if m: names |= {n.strip().split(':')[0].strip() for n in m[-1].group(1).split(',') if re.match(r'\s*[A-Za-z_]\w*\s*(:|$)', n)}
    names |= set(re.findall(r"case\s+'(\w+)'", t)) | set(re.findall(r"^\s{2,6}(\w+)\s*[:(]\s*(?:function|\(|\w+\s*=>)", t, re.M))
    return sorted(n for n in names if n and len(n) > 2 and n not in {'init', 'ctx', 'set', 'get', 'stop', 'start', 'mute', 'unmute', 'resume', 'isMuted', 'setMuted', 'loadVoices', 'loop', 'lrCheck', 'say', 'setTimeout', 'tone', 'voiceLevel', 'voice', 'voicePending', 'setRoom', 'speak', 'play'})


def build():
    L = ['# Asset library', '', 'Generated by `python3 tools/library/index.py` — do not edit by hand. Reuse rule (guide §12.1): never load another',
         "demo's file; same category → move it into `demos/<category>/_kit/`, other category → copy it. Character cards: `docs/characters/`.", '']
    plates = images('**/media/art/bg_*') + images('_kit/**/*bg*') + images('_kit/places/*')
    L += ['## Background plates (empty scenes)', '', '| plate | size | where |', '|---|---|---|']
    for p in sorted(set(plates)): L.append(f'| `{os.path.basename(p)}` | {size(p)} | `{rel(p)}` |')
    props = images('**/media/art/prop_*') + images('**/media/art/fx_*') + images('_kit/**/prop_*') + images('_kit/**/fx_*')
    L += ['', '## Props and FX sprites', '', '| sprite | size | where |', '|---|---|---|']
    for p in sorted(set(props)): L.append(f'| `{os.path.basename(p)}` | {size(p)} | `{rel(p)}` |')
    L += ['', '## Character layers (cut-out poses, for reference / new angles — see the character card first)', '', '| demo | poses |', '|---|---|']
    by = {}
    for p in images('**/media/art/char_*') + images('_kit/art/*_pose_*') + images('_kit/art/*_bust_base*'):
        c, d = owner(p); by.setdefault(f'{c}/{d}', []).append(os.path.splitext(os.path.basename(p))[0])
    for k in sorted(by): L.append(f'| `{k}` | {", ".join(sorted(by[k]))} |')
    L += ['', '## Code effects (demos/shared, any demo)', '']
    for f in ('layers.js', 'fireworks.js', 'gesture.js'):
        p = os.path.join(REPO, 'demos', 'shared', f)
        if os.path.exists(p): L.append(f'- `demos/shared/{f}` — ' + (open(p, encoding='utf-8').readline().strip('/ \n')[:160]))
    L += ['', '## Synthesized SFX (Web Audio, per demo / kit `audio.js`)', '', '| module | sounds / functions |', '|---|---|']
    for p in sorted(glob.glob(os.path.join(REPO, 'demos', '*', '*', 'audio.js')) + glob.glob(os.path.join(REPO, 'demos', '*', '_kit', '*', 'audio.js'))):
        n = sfx_names(p)
        if n: L.append(f'| `{rel(p)}` | {", ".join(n[:30])}{" …" if len(n) > 30 else ""} |')
    rec = [p for p in glob.glob(os.path.join(REPO, 'demos', '*', '*', 'media', '**', '*'), recursive=True)
           if p.lower().endswith(('.mp3', '.m4a', '.wav', '.ogg')) and not re.search(r'/voice/|voice_|/lines?/', p)]
    L += ['', '## Recorded music / SFX files', '']
    L += [f'- `{rel(p)}`' for p in sorted(rec)] or ['- (none)']
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    text = build()
    if '--print' in sys.argv: print(text); sys.exit(0)
    out = os.path.join(REPO, 'docs', 'library.md'); tmp = out + '.tmp'
    open(tmp, 'w', encoding='utf-8').write(text); os.replace(tmp, out)
    print(f'wrote docs/library.md ({text.count(chr(10))} lines)')
