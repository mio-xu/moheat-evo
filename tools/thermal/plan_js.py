#!/usr/bin/env python3
"""Thermal plan → page data (DEMO_DESIGN_GUIDE §3 DUAL; the story engine demos/shared/story.js).

  python3 tools/thermal/plan_js.py <demo folder>

Reads <demo>/project/thermal_plan.json (the same file tools/thermal/plan_sim.py simulates: voice distances, smoothing, events with
set / pulse / sweep / then, step_start, places) and, when present, <demo>/project/talk_views.json ("reuse": place|who → view for
もっと話す) and writes <demo>/media/plan.js = window.MOHEAT_PLAN = { voice, smoothing, events, step_start, places, reuse }.
One source: edit thermal_plan.json, rerun this (and plan_sim.py), then tools/web/bump.py --auto. The '_doc' / 'why' texts stay
in the project file (they are for people, not for the page)."""
import json, os, sys

D = os.path.abspath(sys.argv[1])
plan = json.load(open(os.path.join(D, 'project', 'thermal_plan.json'), encoding='utf-8'))
ev = {k: {x: y for x, y in v.items() if x != 'why'} for k, v in plan['events'].items()}
out = {'voice': plan['voice'], 'smoothing': plan['smoothing'], 'events': ev, 'step_start': plan.get('step_start') or {},
       'places': plan.get('places') or {}}
tv = os.path.join(D, 'project', 'talk_views.json')
if os.path.exists(tv): out['reuse'] = json.load(open(tv, encoding='utf-8')).get('reuse', {})
os.makedirs(os.path.join(D, 'media'), exist_ok=True)
head = ('// Thermal plan of this demo for ../../shared/story.js (DUAL: set / pulse / sweep / then per event, voice distances, smoothing).\n'
        '// GENERATED by tools/thermal/plan_js.py from project/thermal_plan.json (+ project/talk_views.json) — edit there, not this file.\n')
open(os.path.join(D, 'media', 'plan.js'), 'w', encoding='utf-8').write(head + 'window.MOHEAT_PLAN = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(os.path.relpath(os.path.join(D, 'media', 'plan.js')), f'{len(ev)} events')
